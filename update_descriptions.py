def update_descriptions():
    """Updates the 'description' for existing courses in the database."""
    conn = sqlite3.connect(DB_FILE)
    cursor = conn.cursor()
    
    try:
        updated_count = 0
        for course_id, description in course_descriptions_to_update.items():
            cursor.execute("UPDATE courses SET description = ? WHERE course_id = ?", (description, course_id))
            if cursor.rowcount > 0:
                updated_count += 1
        
        conn.commit()
        print(f"✅ Successfully updated descriptions for {updated_count} courses.")

    except Exception as e:
        print(f"❌ An error occurred: {e}")
    finally:
        conn.close()

if __name__ == "__main__":
    update_descriptions()